#!/usr/bin/env python3
"""Embed the generated INCY deeplinks into the potato-link Worker."""

from __future__ import annotations

import argparse
import base64
import binascii
import json
import re
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
INCY_DEFAULT_INPUT = REPO_ROOT / "INCY/DEFAULT.DEEPLINK"
INCY_RU_INPUT = REPO_ROOT / "INCY/RU-VPN.DEEPLINK"
DEFAULT_OUTPUT = REPO_ROOT / "cloudflare/potato-link/dist/destinations.js"
INCY_DEEPLINK_PREFIX = "incy://routing/onadd/"
INCY_DEEPLINK_PREFIXES = (INCY_DEEPLINK_PREFIX, "incy://routing/add/")
MAX_DEEPLINK_LENGTH = 16 * 1024
BASE64_RE = re.compile(r"[A-Za-z0-9+/]+={0,2}")


def validate_deeplink(raw: str, path: Path, scheme: str = "incy") -> str:
    lines = raw.splitlines()
    if len(lines) != 1 or not lines[0]:
        raise ValueError(f"{path}: deeplink must be a single line")
    value = lines[0]
    if len(value) > MAX_DEEPLINK_LENGTH:
        raise ValueError(f"{path}: deeplink exceeds 16 KiB")
    prefixes = {
        "incy": INCY_DEEPLINK_PREFIXES,
    }
    try:
        allowed_prefixes = prefixes[scheme]
    except KeyError as exc:
        raise ValueError(f"{path}: unsupported deeplink scheme {scheme!r}") from exc
    prefix = next((candidate for candidate in allowed_prefixes if value.startswith(candidate)), None)
    if prefix is None:
        raise ValueError(f"{path}: unexpected deeplink prefix")
    payload = value.removeprefix(prefix)
    if BASE64_RE.fullmatch(payload) is None:
        raise ValueError(f"{path}: invalid base64 payload")
    try:
        decoded = base64.b64decode(payload, validate=True)
    except (binascii.Error, ValueError) as exc:
        raise ValueError(f"{path}: invalid base64 payload") from exc
    if base64.b64encode(decoded).decode("ascii") != payload:
        raise ValueError(f"{path}: invalid base64 payload")
    return value


def read_deeplink(path: Path, scheme: str = "incy") -> str:
    return validate_deeplink(path.read_text(encoding="utf-8"), path, scheme=scheme)


def build_module(incy_default: str, incy_ru: str) -> str:
    return (
        "// Generated by scripts/build_potato_link_worker.py; do not edit.\n"
        "export const DESTINATIONS = Object.freeze({\n"
        f"  incyDefault: {json.dumps(incy_default)},\n"
        f"  incyRu: {json.dumps(incy_ru)},\n"
        "});\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--incy-default-input", type=Path, default=INCY_DEFAULT_INPUT)
    parser.add_argument("--incy-ru-input", type=Path, default=INCY_RU_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    output = build_module(
        read_deeplink(args.incy_default_input, scheme="incy"),
        read_deeplink(args.incy_ru_input, scheme="incy"),
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
